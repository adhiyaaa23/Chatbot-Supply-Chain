def compute_risk_score(
    current_stock: int,
    inventory_plan: dict,
    forecast_result: dict,
) -> dict:
    """
    [UPGRADE v2] Risk Score multi-dimensi (0–100) dengan breakdown.
    - v1: satu angka sederhana berbasis ROP gap saja
    - v2: Inventory Gap + Demand Uncertainty + Criticality Weight
    """
    ss  = inventory_plan["safety_stock"]
    rop = inventory_plan["reorder_point"]
    crit = inventory_plan["criticality"]

    crit_w = {"CRITICAL": 1.5, "HIGH": 1.2, "MEDIUM": 1.0}.get(crit, 1.0)
    stock_ratio = current_stock / (rop + 1e-9)

    # Inventory Risk
    inv_risk = int(np.clip(max(0, (1 - stock_ratio) * 60)
                           * crit_w + (15 if current_stock <= ss else 0), 0, 100))

    # Demand Uncertainty Risk
    fc = forecast_result["ensemble_forecast"]
    cv_fc = float(np.std(fc) / (np.mean(fc) + 1e-9))
    demand_risk = int(np.clip(cv_fc * 80, 0, 100))

    # Coverage Risk (stok habis dalam berapa bulan)
    avg_fc = float(np.mean(fc))
    months_cover = current_stock / (avg_fc + 1e-9)
    cover_risk = int(np.clip(max(0, (3 - months_cover) / 3 * 60) * crit_w, 0, 100))

    composite = int(0.40 * inv_risk + 0.30 * demand_risk + 0.30 * cover_risk)
    level = ("🔴 KRITIS" if composite >= 70 else
             "🟠 TINGGI" if composite >= 45 else
             "🟡 SEDANG" if composite >= 25 else
             "🟢 RENDAH")

    return {
        "composite_score": composite,
        "level":           level,
        "inventory_risk":  inv_risk,
        "demand_risk":     demand_risk,
        "coverage_risk":   cover_risk,
        "months_cover":    round(months_cover, 1),
    }


