def run_nexusgen_pipeline(
    selected_part: str = "Kampas Rem Besar",
    current_stock: int = 4,
    claude_api_key: str = "",
    export_reports: bool = True,
    save_visual: bool = True,
) -> dict:
    """
    Pipeline lengkap NexusGen v2.0:
    1.  Data 48 bulan, 8 parts, Negative Binomial
    2.  Forecast: Prophet + HGB ensemble (6 bulan, dengan CI)
    3.  Dynamic Safety Stock: ABC-XYZ + variance lead time
    4.  Risk Score multi-dimensi
    5.  Claude AI Insight (gantikan Gemini)
    6.  Dashboard 10 panel
    7.  JSON export per part
    """
    print("=" * 65)
    print("  NexusGen v2.0 – Gen-AI Supply Chain Oracle")
    print("  Astra UD Trucks | Prophet · HGB · ABC-XYZ · Claude AI")
    print("=" * 65 + "\n")

    # 1. Data
    print("📦 [1/5] Simulasi data demand (48 bln, 8 parts, Neg. Binomial)...")
    df = generate_intermittent_demand_data()

    # 2–4. Analisis semua parts
    print(f"🔍 [2/5] Menganalisis {len(SPARE_PARTS_CATALOG)} suku cadang...\n")
    all_results: dict[str, dict] = {}

    for pname, pinfo in SPARE_PARTS_CATALOG.items():
        print(f"  ▸ {pname}")
        p_demand = df[df["part_name"] == pname].sort_values("date")
        d_series = p_demand["demand"].values
        d_dates  = pd.DatetimeIndex(p_demand["date"].values)

        fc  = forecast_demand(d_series, d_dates)
        inv = calculate_safety_stock(d_series, part_name=pname,
                                      unit_cost=pinfo["unit_cost"],
                                      criticality=pinfo["criticality"])
        rs  = compute_risk_score(current_stock, inv, fc)
        all_results[pname] = {"fc": fc, "inv": inv, "risk": rs}

    print()

    # 5. Detail & AI untuk part yang dipilih
    profile = all_results[selected_part]
    fc_r    = profile["fc"]
    inv_r   = profile["inv"]
    risk_r  = profile["risk"]

    print(f"{'─'*60}")
    print(f"📋 DETAIL ANALISIS: {selected_part}")
    print(f"{'─'*60}")
    print(f"   ABC={inv_r['abc_class']} | XYZ={inv_r['xyz_class']} | "
          f"CV={inv_r['cv']} | Criticality={inv_r['criticality']}")
    print(f"   Safety Stock : {inv_r['safety_stock']} unit")
    print(f"   ROP          : {inv_r['reorder_point']} unit")
    print(f"   EOQ          : {inv_r['eoq']} unit")
    print(f"   Forecast 6 bln: {[round(v,1) for v in fc_r['ensemble_forecast'].tolist()]}")
    print(f"   Risk Score   : {risk_r['composite_score']}/100 ({risk_r['level']})")
    print(f"   Stok saat ini: {current_stock} unit | Cover: {risk_r['months_cover']} bln\n")

    print(f"{'─'*60}")
    print("🤖 [3/5] Meminta AI Insight dari Claude...")
    print(f"{'─'*60}")
    ai_insight = get_ai_recommendation(
        selected_part, inv_r, fc_r, risk_r, current_stock,
        api_key=claude_api_key,
    )
    print(ai_insight)

    # Summary tabel
    summary = pd.DataFrame([{
        "Suku Cadang": p,
        "ABC-XYZ":    v["inv"]["abc_class"] + v["inv"]["xyz_class"],
        "Forecast/Bln": round(float(np.mean(v["fc"]["ensemble_forecast"])), 1),
        "Safety Stock": v["inv"]["safety_stock"],
        "ROP":          v["inv"]["reorder_point"],
        "EOQ":          v["inv"]["eoq"],
        "Risk Score":   v["risk"]["composite_score"],
        "Risk Level":   v["risk"]["level"],
    } for p, v in all_results.items()])

    print(f"\n{'─'*60}")
    print("📊 [4/5] RINGKASAN SEMUA SUKU CADANG:")
    print(f"{'─'*60}")
    print(summary.to_string(index=False))

    # Dashboard & Export
    if save_visual:
        print(f"\n📈 [5/5] Membuat Dashboard (10 panel)...")
        visualize_nexusgen(df, selected_part, inv_r, fc_r,
                           risk_r, all_results)

    if export_reports:
        export_analysis_report(selected_part, inv_r, fc_r, risk_r, ai_insight)

    print("✅ NexusGen v2.0 Pipeline selesai!")

    return {
        "df":          df,
        "all_results": all_results,
        "selected":    selected_part,
        "fc":          fc_r,
        "inv":         inv_r,
        "risk":        risk_r,
        "ai_insight":  ai_insight,
        "summary":     summary,
    }


