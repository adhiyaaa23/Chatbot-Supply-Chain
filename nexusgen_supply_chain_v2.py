def export_analysis_report(
    part_name: str,
    inventory_plan: dict,
    forecast_result: dict,
    risk_score: dict,
    ai_insight: str,
) -> Path:
    safe_name = part_name.replace(" ", "_").lower()
    path = CFG.output_dir / f"report_{safe_name}_v2.json"
    report = {
        "platform":   "NexusGen v2.0",
        "part_name":  part_name,
        "inventory":  {k: v for k, v in inventory_plan.items()},
        "forecast": {
            "method":   forecast_result["method"],
            "horizon":  forecast_result["horizon"],
            "values":   [round(v, 2) for v in forecast_result["ensemble_forecast"].tolist()],
            "lower":    [round(v, 2) for v in forecast_result["lower_bound"].tolist()],
            "upper":    [round(v, 2) for v in forecast_result["upper_bound"].tolist()],
            "croston_baseline": round(forecast_result["croston_next"], 2),
        },
        "risk_score": risk_score,
        "ai_insight": ai_insight,
    }
    with path.open("w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    print(f"📁 Laporan disimpan: {path}")
    return path


