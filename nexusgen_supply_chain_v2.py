def generate_intermittent_demand_data(
    n_months: int = CFG.n_months,
    seed: int = 42,
) -> pd.DataFrame:
    """
    [UPGRADE v2] Data demand 48 bulan (dari 36), 8 parts (dari 5).
    - Distribusi Negative Binomial menggantikan Poisson
      (lebih realistis untuk demand intermittent dengan over-dispersion)
    - Seasonal pattern 2 puncak (Q4 + Q3) menggantikan 1 puncak (Q4 saja)
    - Tren non-linear (logistik) menggantikan tren linear
    - Tambah kolom: unit_cost, criticality, quarter
    """
    np.random.seed(seed)
    date_range = pd.date_range(start="2021-01-01", periods=n_months, freq="MS")
    records: list[dict] = []

    for part_name, params in SPARE_PARTS_CATALOG.items():
        for i, date in enumerate(date_range):
            # Dua musim puncak (baru)
            seasonal_boost = (
                1.9 if date.month in [11, 12, 1] else   # Q4/awal tahun
                1.4 if date.month in [6, 7, 8]  else    # pertengahan tahun (baru)
                1.0
            )
            # Tren logistik (lebih realistis dari linear)
            trend_factor = 1 + 0.35 / (1 + np.exp(-0.15 * (i - n_months / 2)))

            prob = min(params["base_prob"] * seasonal_boost * trend_factor, 0.97)
            demand_occurs = np.random.binomial(1, prob)

            if demand_occurs:
                # Negative Binomial – lebih over-dispersed dari Poisson (baru)
                expected_qty = params["base_qty"] * seasonal_boost
                r = max(1, int(expected_qty))
                p_nb = r / (r + expected_qty)
                qty = int(np.random.negative_binomial(r, p_nb)) + 1
            else:
                qty = 0

            records.append({
                "date":        date,
                "part_name":   part_name,
                "demand":      qty,
                "month":       date.month,
                "year":        date.year,
                "quarter":     date.quarter,
                "unit_cost":   params["unit_cost"],
                "criticality": params["criticality"],
                "seasonal_factor": round(seasonal_boost, 2),
            })

    df = pd.DataFrame(records)
    print("✅ Dataset Intermittent Demand berhasil dibuat.")
    print(f"   Periode  : {df['date'].min().strftime('%b %Y')} – "
          f"{df['date'].max().strftime('%b %Y')} ({n_months} bulan)")
    print(f"   Parts    : {df['part_name'].nunique()} (v1: 5)")
    print(f"   Records  : {len(df):,}")
    print(f"   Distribusi qty: Negative Binomial (v1: Poisson)\n")
    return df


def describe_data_quality(df: pd.DataFrame) -> pd.DataFrame:
    """Ringkasan kualitas data per part."""
    return (
        df.groupby("part_name")["demand"]
        .agg(["count", "sum", "mean", "std", "nunique"])
        .rename(columns={"count": "records", "sum": "total_demand",
                         "mean": "avg_demand", "std": "std_demand",
                         "nunique": "unique_values"})
        .reset_index()
    )


