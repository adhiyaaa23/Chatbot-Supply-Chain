def _fallback_recommendation(
    part_name: str,
    inv: dict,
    fc: dict,
    risk: dict,
    current_stock: int,
) -> str:
    avg_fc = float(np.mean(fc["ensemble_forecast"]))
    months = risk["months_cover"]
    decision = (
        "🔴 PESAN DARURAT SEKARANG"  if current_stock <= 0 else
        "🔴 BELI SEKARANG"           if current_stock <= inv["safety_stock"] else
        "🟠 PESAN SEGERA"            if current_stock <= inv["reorder_point"] else
        "🟡 RENCANAKAN PO"           if months < 3 else
        "🟢 TAHAN STOK"
    )
    action = (
        f"Buat PO darurat {inv['eoq']} unit, prioritaskan pengiriman ekspres."
        if current_stock <= inv["reorder_point"] else
        f"Pantau harian; buat PO {inv['eoq']} unit saat stok = {inv['reorder_point']}."
    )
    return f"""🎯 KEPUTUSAN UTAMA: {decision}

📊 ANALISIS (ABC={inv['abc_class']}, XYZ={inv['xyz_class']}):
   Stok {current_stock} unit mencukupi ≈{months:.1f} bulan dengan forecast rata-rata {avg_fc:.1f} unit/bln.
   Risk Score {risk['composite_score']}/100 ({risk['level']}).
   CV={inv['cv']:.2f} menunjukkan demand {'stabil' if inv['xyz_class']=='X' else 'cukup bervariasi' if inv['xyz_class']=='Y' else 'sangat tidak menentu'}.

⚡ TINDAKAN KONKRET:
   1. {action}
   2. Konfirmasi lead time supplier ({inv['lead_time']} bulan) dan minta komitmen tertulis.
   3. Set alert otomatis di sistem WMS saat stok menyentuh ROP={inv['reorder_point']}.

⚠️ RISIKO JIKA TIDAK BERTINDAK:
   Downtime produksi akibat stockout {part_name} (criticality: {inv['criticality']}) dapat
   mengakibatkan kerugian produksi >> Rp {inv['unit_cost']:,} per insiden.

💡 REKOMENDASI JANGKA PANJANG:
   Part ABC={inv['abc_class']}/XYZ={inv['xyz_class']}: {'pertimbangkan VMI (vendor-managed inventory)' if inv['abc_class']=='A' else 'review safety stock setiap kuartal' if inv['abc_class']=='B' else 'konsolidasikan order dengan part C lainnya'}.
"""


# backward-compat: alias lama tetap berfungsi
def get_gemini_recommendation(part_name, croston, safety, lstm_forecasts,
                               current_stock, api_key=None):
    """Alias untuk kompatibilitas mundur. Sekarang memanggil Claude."""
    fc_arr = np.asarray(lstm_forecasts, dtype=float)
    mock_fc = {
        "ensemble_forecast": fc_arr,
        "lower_bound":       np.maximum(0, fc_arr * 0.7),
        "upper_bound":       fc_arr * 1.3,
        "croston_next":      croston.get("next_forecast", 0),
        "method":            "Legacy (via get_gemini_recommendation alias)",
        "horizon":           len(fc_arr),
    }
    mock_risk = {
        "composite_score": compute_risk_score(
            current_stock, safety, mock_fc)["composite_score"],
        "level": "", "inventory_risk": 0,
        "demand_risk": 0, "coverage_risk": 0, "months_cover": 0,
    }
    mock_risk.update(compute_risk_score(current_stock, safety, mock_fc))
    return get_ai_recommendation(part_name, safety, mock_fc, mock_risk,
                                  current_stock, api_key or "")


