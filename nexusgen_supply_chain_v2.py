def forecast_demand(
    demand_series: np.ndarray,
    dates: pd.DatetimeIndex,
    horizon: int = CFG.forecast_horizon,
) -> dict:
    """
    [UPGRADE v2] Metode forecast diprioritaskan:
    1. Prophet (Meta) – jika tersedia (pip install prophet)
       Unggulan untuk data musiman & intermittent
    2. HGB Gradient Boosting dengan lag features yang diperkaya
       (Menggantikan lstm_forecast yang sebelumnya hanya alias HGB)
    3. Croston SBA – dipertahankan sebagai sanity check / baseline

    Jika Prophet tersedia → ensemble Prophet(0.6) + HGB(0.4)
    Jika tidak → HGB saja (tetap jauh lebih baik dari Croston sendiri)
    """
    series = np.asarray(demand_series, dtype=float)

    # ── Metode 1: Prophet ──
    prophet_forecast = None
    try:
        from prophet import Prophet
        df_p = pd.DataFrame({"ds": dates, "y": series})
        m = Prophet(
            yearly_seasonality=True,
            weekly_seasonality=False,
            daily_seasonality=False,
            seasonality_mode="multiplicative",
            changepoint_prior_scale=0.05,
            interval_width=0.80,
        )
        m.fit(df_p, iter=300)
        future = m.make_future_dataframe(periods=horizon, freq="MS")
        fc = m.predict(future)
        prophet_forecast = {
            "mean":  np.maximum(0, fc["yhat"].values[-horizon:]),
            "lower": np.maximum(0, fc["yhat_lower"].values[-horizon:]),
            "upper": np.maximum(0, fc["yhat_upper"].values[-horizon:]),
        }
    except ImportError:
        pass
    except Exception as e:
        print(f"   ⚠️  Prophet error: {e}")

    # ── Metode 2: HGB dengan lag features diperkaya ──
    n_lag = min(12, len(series) // 2)
    if len(series) >= n_lag + 2:
        feat_df = pd.DataFrame({"demand": series})
        for lag in range(1, n_lag + 1):
            feat_df[f"lag_{lag}"] = feat_df["demand"].shift(lag)
        feat_df["trend"]     = np.arange(len(feat_df), dtype=float)
        feat_df["month"]     = (np.arange(len(feat_df)) % 12) + 1
        feat_df["quarter"]   = ((np.arange(len(feat_df)) % 12) // 3) + 1
        feat_df["sin_month"] = np.sin(2 * np.pi * feat_df["month"] / 12)
        feat_df["cos_month"] = np.cos(2 * np.pi * feat_df["month"] / 12)
        feat_df["roll3_mean"] = feat_df["demand"].shift(1).rolling(3).mean()
        feat_df["roll6_mean"] = feat_df["demand"].shift(1).rolling(6).mean()
        feat_df = feat_df.dropna().reset_index(drop=True)

        feat_cols = [c for c in feat_df.columns if c != "demand"]
        model = HistGradientBoostingRegressor(
            max_iter=400, learning_rate=0.05,
            max_leaf_nodes=24, l2_regularization=0.2, random_state=42,
        )
        model.fit(feat_df[feat_cols].values, feat_df["demand"].values)

        last_window = list(series[-n_lag:])
        hgb_preds: list[float] = []
        for step in range(horizon):
            t   = float(len(series) + step)
            m_v = float((len(series) + step) % 12 + 1)
            q_v = float(((len(series) + step) % 12) // 3 + 1)
            r3  = float(np.mean(last_window[-3:])) if len(last_window) >= 3 else float(np.mean(last_window))
            r6  = float(np.mean(last_window[-6:])) if len(last_window) >= 6 else float(np.mean(last_window))
            feats = (last_window[-n_lag:]
                     + [t, m_v, q_v,
                        np.sin(2 * np.pi * m_v / 12),
                        np.cos(2 * np.pi * m_v / 12),
                        r3, r6])
            pred = float(max(0, model.predict(np.array(feats).reshape(1, -1))[0]))
            hgb_preds.append(pred)
            last_window.append(pred)
        hgb_forecast = np.array(hgb_preds)
    else:
        hgb_forecast = np.full(horizon, float(series.mean()))

    # ── Croston SBA (baseline) ──
    croston_next = _croston_sba(series)

    # ── Ensemble ──
    if prophet_forecast is not None:
        ensemble = 0.6 * prophet_forecast["mean"] + 0.4 * hgb_forecast
        method = "Prophet(0.6) + HGB(0.4)"
        lower  = prophet_forecast["lower"]
        upper  = prophet_forecast["upper"]
    else:
        ensemble = hgb_forecast
        method   = "HGB Boosting (install Prophet untuk hasil lebih akurat: pip install prophet)"
        std_fc   = hgb_forecast.std() * 0.5
        lower    = np.maximum(0, hgb_forecast - std_fc)
        upper    = hgb_forecast + std_fc

    return {
        "ensemble_forecast": np.maximum(0, ensemble),
        "hgb_forecast":      hgb_forecast,
        "prophet_forecast":  prophet_forecast,
        "croston_next":      croston_next,
        "lower_bound":       lower,
        "upper_bound":       upper,
        "method":            method,
        "horizon":           horizon,
    }


def _croston_sba(demand: np.ndarray, alpha: float = 0.1) -> float:
    """Croston SBA – dipertahankan sebagai baseline check."""
    demand = np.asarray(demand, dtype=float)
    nz = np.where(demand > 0)[0]
    if len(nz) == 0:
        return 0.0
    a_t = demand[nz].mean()
    p_t = float(np.diff(np.concatenate(([-1], nz))).mean())
    for i, d in enumerate(demand):
        if d > 0:
            a_t = alpha * d + (1 - alpha) * a_t
            p_t = alpha * max(1, i) + (1 - alpha) * p_t
    return float((1 - alpha / 2) * a_t / max(p_t, 1e-6))


# backward-compat alias (agar kode lama tetap jalan)
def crostons_method(demand_series, alpha=0.1, variant="sba"):
    demand = np.asarray(demand_series, dtype=float)
    fc_next = _croston_sba(demand, alpha)
    return {"next_forecast": fc_next, "variant": variant}


